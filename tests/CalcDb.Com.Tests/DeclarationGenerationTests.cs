using System.Globalization;
using System.Text;
using CalcDb.Evidence;

namespace CalcDb.Com.Tests;

/// <summary>
/// The DAO declarations CalcDb.dll lays out are generated from the captured type library (II-13 §2: one reconciled
/// manifest, R-ACT-1 ACT-DECL). This test renders them and requires the checked-in file to match; with
/// CALCDB_REGENERATE=1 it rewrites the file instead.
/// </summary>
public sealed class DeclarationGenerationTests
{
    internal const string Record = "evidence/r-dao-1-err-1/manifest-library/r-dao-1-err-1.manifest-library.bab1b7935f.a2.json";

    /// <summary>The interfaces generated so far, by the slice that needs them.</summary>
    private static readonly string[] Interfaces = ["_DBEngine"];

    internal static string Root()
    {
        string root = AppContext.BaseDirectory;
        while (!File.Exists(Path.Combine(root, "CalcDb.slnx")))
        {
            root = Path.GetDirectoryName(root)!;
        }
        return root;
    }

    [Fact]
    public void The_generated_declarations_match_the_captured_type_library()
    {
        string root = Root();
        EvidenceRecord record = EvidenceJson.Read<EvidenceRecord>(Path.Combine(root, Record));
        TypeEvent types = record.Capture!.Events.OfType<TypeEvent>().Single();
        string rendered = Render(types);
        string target = Path.Combine(root, "src", "CalcDb.Com", "Declarations", "Dao.g.cs");
        if (Environment.GetEnvironmentVariable("CALCDB_REGENERATE") == "1")
        {
            File.WriteAllText(target, rendered);
        }
        Assert.Equal(rendered, File.ReadAllText(target).ReplaceLineEndings("\n"));
    }

    private static string Render(TypeEvent types)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/>\n");
        sb.Append("// Generated by DeclarationGenerationTests from the captured DAO type library (R-ACT-1 ACT-DECL):\n");
        sb.Append($"// {Record}\n");
        sb.Append($"// library {types.Library!.Name} {types.Library.Guid} {types.Library.Major}.{types.Library.Minor}. Do not edit; regenerate with CALCDB_REGENERATE=1.\n");
        sb.Append("using System.Runtime.InteropServices;\n\nnamespace CalcDb.Com.Declarations;\n\n");
        sb.Append("internal static unsafe partial class Dao\n{\n");
        var stubs = new StringBuilder();
        foreach (string name in Interfaces)
        {
            TypeView dispatch = types.Types.Single(t => t.Name == name && t.TypeKind == 4);
            TypeView dual = dispatch.DualInterface ?? throw new InvalidOperationException(name + " is not dual");
            FunctionInfo[] members = dispatch.Functions.Where(f => f.VtableOffset >= 56).ToArray();
            foreach (FunctionInfo v in dual.Functions)
            {
                // The vtable view must agree with the dispatch view on every slot it lists.
                Assert.Contains(members, m => m.MemberId == v.MemberId && m.InvokeKind == v.InvokeKind && m.VtableOffset == v.VtableOffset);
            }
            string id = name.TrimStart('_');
            sb.Append($"    public static readonly InterfaceDecl {id} = new(\"{name}\", new Guid(\"{dispatch.Guid.Trim('{', '}')}\"), {dual.VtableBytes},\n    [\n");
            foreach (FunctionInfo f in members)
            {
                string ps = string.Join(", ", f.Parameters.Select(p => $"new(\"{p.Name}\", \"{p.Type}\", 0x{p.Flags:X})"));
                sb.Append($"        new({f.MemberId}, \"{f.Name}\", (InvokeKind){f.InvokeKind}, {f.VtableOffset}, \"{f.ReturnType}\", [{ps}]),\n");
            }
            sb.Append($"    ], &Fill_{id});\n\n");
            stubs.Append($"    private static void Fill_{id}(nint* table)\n    {{\n");
            var body = new StringBuilder();
            foreach (FunctionInfo f in members)
            {
                int slot = f.VtableOffset / 8;
                bool hasRetval = f.ReturnType != "VT_VOID";
                int arity = f.Parameters.Count + (hasRetval ? 1 : 0);
                string sig = string.Concat(Enumerable.Repeat("nint, ", arity + 1)) + "int";
                stubs.Append($"        table[{slot}] = (nint)(delegate* unmanaged<{sig}>)&U_{id}_{slot};\n");
                string args = string.Concat(Enumerable.Range(0, arity).Select(k => $", nint a{k}"));
                string retval = hasRetval ? $"a{arity - 1}" : "0";
                body.Append($"\n    [UnmanagedCallersOnly]\n    private static int U_{id}_{slot}(nint self{args}) => Com.Unimplemented.Fail(self, {id}, {slot}, {retval}, RetvalCell.{Cell(f.ReturnType)});\n");
            }
            stubs.Append("    }\n").Append(body);
        }
        sb.Append(stubs.ToString().TrimEnd('\n')).Append('\n');
        sb.Append("}\n");
        return sb.ToString();
    }

    private static string Cell(string returnType) => returnType switch
    {
        "VT_VOID" => "None",
        "VT_UI1" => "Byte",
        "VT_I2" or "VT_BOOL" or "VT_UI2" => "Int16",
        "VT_I4" or "VT_UI4" or "VT_INT" or "VT_UINT" or "VT_R4" or "VT_HRESULT" or "VT_ERROR" => "Int32",
        "VT_VARIANT" => "Variant",
        _ when returnType.StartsWith("PTR ", StringComparison.Ordinal) || returnType is "VT_BSTR" or "VT_DISPATCH" or "VT_UNKNOWN" or "VT_R8" or "VT_DATE" or "VT_CY" or "VT_I8" or "VT_UI8" => "Pointer",
        _ => throw new InvalidOperationException("no retval cell rule for " + returnType),
    };
}
